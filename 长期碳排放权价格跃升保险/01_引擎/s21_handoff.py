def d1_engine_snapshot() -> pd.DataFrame:
    """引擎快照同步表：work copy MD5 vs 三个快照目录。"""
    rows = []
    for p in sorted(ENGINE.glob("*.py")):
        rec = {"脚本": p.name, "工作副本 MD5": md5(p)[:12], "大小(B)": p.stat().st_size}
        for tag, snap in SNAPSHOTS.items():
            q = snap / p.name
            if not q.exists():
                rec[tag] = "—"
            elif md5(q) == md5(p):
                rec[tag] = "一致"
            else:
                rec[tag] = "**不一致**"
        rows.append(rec)
    return pd.DataFrame(rows)


