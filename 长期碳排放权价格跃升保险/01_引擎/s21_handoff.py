def load(name: str, out: Path = None) -> pd.DataFrame:
    p = (out or OUT) / name
    if not p.exists():
        raise FileNotFoundError(f"缺少上游产物：{p}")
    return pd.read_csv(p, encoding="utf-8-sig")


def md5(p: Path) -> str:
    h = hashlib.md5()
    with open(p, "rb") as f:
        for blk in iter(lambda: f.read(1 << 16), b""):
            h.update(blk)
    return h.hexdigest()


