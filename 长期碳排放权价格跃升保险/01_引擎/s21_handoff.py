def build_config(DELIV, PROD, SNAP, HAND, CARDS) -> dict:
    return {
        "工作包": ["D1 交付包封装", "D2 短期线交接", "D3 团队引用规范"],
        "接触主体": CONTACT, "性质": TITLE,
        "D1": {"交付物份数": len(DELIV), "产物文件数": len(PROD),
               "引擎脚本数": len(SNAP),
               "快照一致": int((SNAP[["deliver3", "deliver4", "deliver4_C1b"]]
                                .apply(lambda s: s.map(lambda v: v == "一致")).sum().sum())),
               "快照不一致": int((SNAP[["deliver3", "deliver4", "deliver4_C1b"]]
                                  .apply(lambda s: s.map(lambda v: v == "**不一致**")).sum().sum()))},
        "D2": {"交接项数": len(HAND),
               "不可改动项": int(HAND["可改动性"].str.contains("不可改|不可收窄|不可放宽|结构性事实")
                                 .sum())},
        "D3": {"卡片数": len(CARDS), "适用线覆盖": sorted(
            {x for s in CARDS["适用线"] for x in s.split(" / ")})},
        "三个待拍板/未决口径": [
            "CAP 全局 vs 逐档（建议全局）",
            "增值税不含税 vs 含税（含税 ×1.0923）",
            "最低资本口径核定期限（Q10，阻塞报价）",
        ],
    }


def acceptance(DELIV, PROD, SNAP, HAND, CARDS, CFG, verbose=True) -> bool:
    res = []

    def add(k, cond, msg=""):
        res.append({"检核项": k, "结果": "PASS" if cond else "FAIL", "说明": msg})

    # ---- D1 ----
    add("D1-01", len(DELIV) >= 12, f"交付物索引 ≥ 12 份（实测 {len(DELIV)}）")
    add("D1-02", DELIV["引用注意事项"].str.len().gt(0).all(), "每份交付物均给出引用注意事项")
    add("D1-03", DELIV["交付物（文件名去扩展）"].is_unique, "交付物名无重复")
    add("D1-04", len(PROD) >= 100, f"产物索引自动扫描（实测 {len(PROD)} 个 CSV）")
    add("D1-05", (PROD["行数"] >= 0).all(), "产物行数均可读（无损坏 CSV）")
    add("D1-06", (PROD["归属工作包"] != "未归类").sum() / len(PROD) > 0.95,
        f"产物归属识别率 {(PROD['归属工作包'] != '未归类').sum() / len(PROD):.1%}")
    add("D1-07", len(SNAP) >= 30, f"引擎快照同步表覆盖 {len(SNAP)} 个脚本")
    snap_n = CFG["D1"]["快照一致"]
    add("D1-08", snap_n > 0, f"快照一致项 {snap_n}（工作副本与快照逐字节一致）")
    # deliver4_C1b 中 s20 必须一致
    s20 = SNAP[SNAP["脚本"] == "s20_downgrade_f3.py"]
    add("D1-09", len(s20) == 1 and s20.iloc[0]["deliver4_C1b"] == "一致",
        "s20 已进入 deliver4 的 C1-β-2/3 快照且一致")

    # ---- D2 ----
    add("D2-01", len(HAND) == 11, f"交接项 11 项（实测 {len(HAND)}）")
    add("D2-02", HAND["来源产物"].str.len().gt(0).all(), "每项交接均标注来源产物（可回溯）")
    add("D2-03", HAND["引用方式"].str.len().gt(0).all(), "每项交接均给出引用方式")
    core = set(HAND["项"])
    need = {"u 路径（合法域边界余量）", "合法域（标度窗口）", "期限弹性", "基差持久性"}
    add("D2-04", need.issubset(core),
        f"规划稿点名的四类固有量齐备（实测缺：{sorted(need - core)}）")
    add("D2-05", int(HAND["可改动性"].str.contains("不可改|不可收窄|不可放宽|结构性事实").sum()) >= 7,
        f"不可改动项 {int(HAND['可改动性'].str.contains('不可改|不可收窄|不可放宽|结构性事实').sum())} 项（≥7）")
    B = load("s1_边界余量诊断.csv")
    u22 = float(B[B["年份"] == 2022].iloc[0]["u"])
    add("D2-06", f"{u22:.6f}" in HAND[HAND["项"].str.startswith("u 路径")].iloc[0]["值"],
        f"u₂₀₂₂ 从 s1_边界余量诊断.csv 读入而非硬编码（{u22:.6f}）")
    K = load("s5_期限一致性.csv")
    add("D2-07", len(K) == 4, "期限弹性来源产物可读（s5_期限一致性.csv 4 行）")

    # ---- D3 ----
    add("D3-01", len(CARDS) == 15, f"口径卡片 15 张（实测 {len(CARDS)}）")
    add("D3-02", CARDS["禁止表述"].str.len().gt(0).all(), "每张卡均含「禁止表述」")
    add("D3-03", CARDS["必须连带的限定语"].str.len().gt(0).all(), "每张卡均含「必须连带的限定语」")
    lines = {x for s in CARDS["适用线"] for x in s.split(" / ")}
    add("D3-04", {"A", "B", "C", "D", "E"}.issubset(lines),
        f"覆盖四条对外线 A/B/C/D/E（实测 {sorted(lines)}）")
    add("D3-05", any("置信区间" in v for v in CARDS["禁止表述"]),
        "含「禁用置信区间表述」——防把模糊性写成概率")
    add("D3-06", any("9.23" in v for v in CARDS["禁止表述"]),
        "含「禁引旧值 9.23」——防口径更正被回退")
    add("D3-07", any("三项门槛" in v for v in CARDS["禁止表述"]),
        "含「禁写三项门槛独立失败」——防三次型裁决被过度声称")
    add("D3-08", any("碳配额质押" in v for v in CARDS["禁止表述"]),
        "含「禁把碳配额质押列为主要信用支持」")

    add("CFG-01", len(CFG["三个待拍板/未决口径"]) == 3, "三个待拍板/未决口径显式登记")
    # 跨批次差异属正常（deliver3 封板时用旧 a0 口径）；要紧的是：
    #   (a) 同批次快照内必须零分歧；(b) 与 deliver3 的分歧集合必须**恰等于**更正登记中的文件集。
    d3_diff = set(SNAP[SNAP["deliver3"] == "**不一致**"]["脚本"])
    d4_diff = set(SNAP[SNAP["deliver4"] == "**不一致**"]["脚本"])
    d4c_diff = set(SNAP[SNAP["deliver4_C1b"] == "**不一致**"]["脚本"])
    corrected = {"v0_cubic_core.py", "v1_cubic_validate.py"}   # deliver4 更正登记点名的两个脚本
    add("CFG-02", d4_diff == set() and d4c_diff == set(),
        f"同批次快照零分歧（deliver4 分歧 {len(d4_diff)}、deliver4_C1b 分歧 {len(d4c_diff)}）")
    add("CFG-03", d3_diff == corrected,
        f"与封板批次 deliver3 的分歧集合**恰等于**更正登记点名的脚本集"
        f"（实测 {sorted(d3_diff)} vs 登记 {sorted(corrected)}）")
    add("CFG-04", len(d3_diff) > 0,
        "跨批次分歧已被显式识别（不是静默漂移）——deliver3 保持原样，可复现性不受损")

    V = pd.DataFrame(res)
    V.to_csv(OUT / "s21_验收.csv", index=False, encoding="utf-8-sig")
    if verbose:
        print(V.to_string(index=False))
        nf = int((V["结果"] == "FAIL").sum())
        print(f"\n  ⇒ {len(V) - nf} PASS / {nf} FAIL")
    return bool((V["结果"] == "PASS").all())


