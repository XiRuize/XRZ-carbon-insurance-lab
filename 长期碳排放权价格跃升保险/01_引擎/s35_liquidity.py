def l2_impact_cost(adv: float, order_size: float,
                   vol_sd: float = 0.6, n_sim: int = 200_000,
                   seed: int = 20261009) -> dict:
    """在给定日成交量分布下，模拟「被动买入 order_size 吨」的成交量加权均价。

    模型：日成交量 V ~ LogNormal(ln(vol_mean), vol_sd)，为成交量分布形状。
          企业买盘占当日成交量的比例 u = min(order_size / V, 1)；
          滑点 s(V) = λ · u^0.5（平方根冲击律，λ 为冲击系数，ⓗ 取 0.05）。
          若 u → 1（买量逼迫当日全部供给），滑点饱和至上限 s_max。
    输出：期望滑点、滑点分布分位、被迫接受极端滑点的概率。
    注：λ 为经验冲击系数，本脚本不声称其为标定值；结论对 λ 的方向不敏感，
        对 u 的量级敏感 —— 因此同时报告 u 的分布。
    """
    rng = np.random.default_rng(seed)
    lam, s_max = 0.05, 0.25
    V = np.exp(rng.normal(np.log(adv), vol_sd, n_sim))
    u = np.minimum(order_size / V, 1.0)
    slip = np.minimum(lam * np.sqrt(u), s_max)
    return {
        "订单量_吨": order_size,
        "日均成交量_吨": adv,
        "订单量占日均比例": order_size / adv,
        "滑点_均值%": float(slip.mean() * 100),
        "滑点_P50%": float(np.median(slip) * 100),
        "滑点_P90%": float(np.quantile(slip, 0.90) * 100),
        "滑点_P99%": float(np.quantile(slip, 0.99) * 100),
        "订单量超过当日成交量的概率%": float((order_size > V).mean() * 100),
        "u_均值": float(u.mean()),
    }


def l2_scenarios() -> pd.DataFrame:
    """三档企业规模 × 两个季节窗口的冲击成本对照。"""
    d = DATUM
    avg = d["2025_年成交量_亿吨"] * 1e8 / 243
    q4_share = 1 - d["2025_前三季度占全年"]
    q4_avg = d["2025_年成交量_亿吨"] * 1e8 * q4_share / 66   # Q4 约 66 交易日
    dec_avg = (d["2025_年成交量_亿吨"] * 1e8 * q4_share
               * (d["2024_12月成交量_万吨"] * 1e4 / (d["2024_年成交量_亿吨"] * 1e8 * d["2024_Q4_10_12月占比"]))) / 22
    # 订单量：企业年度缺口规模（ⓗ 三档）
    orders = {"大型集团（缺口 500 万吨）": 5.0e6,
              "中型企业（缺口 50 万吨）": 5.0e5,
              "小型企业（缺口 5 万吨）": 5.0e4}
    rows = []
    for name, o in orders.items():
        for wname, adv in (("非履约期（全年日均）", avg),
                           ("履约季（四季度日均）", q4_avg),
                           ("履约峰值（12 月日均）", dec_avg)):
            r = l2_impact_cost(adv, o)
            r.update({"企业档": name, "窗口": wname})
            rows.append(r)
    return pd.DataFrame(rows)


