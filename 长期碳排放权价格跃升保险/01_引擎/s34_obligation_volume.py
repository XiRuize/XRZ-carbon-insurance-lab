    print("\n【制度输入 · 逐项可核验】")
    for k in ("出处", "综合基准值年度降幅_编制说明", "履约缺口率20%上限豁免",
              "三行业强度系数法盈缺封顶", "清缴截止日"):
        print(f"  {k}: {DATUM[k]}")

    d1 = q1_determinism()
    print("\n【Q1 义务量可预知性拆解（乘性链条逐环节）】")
    print(d1[["环节", "事前可知"]].to_string(index=False))
