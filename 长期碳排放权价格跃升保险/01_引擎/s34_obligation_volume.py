# ─────────────────────────────────────────────── Q2 义务量变动量级
def q2_magnitude() -> pd.DataFrame:
    """把「基准值收紧」翻译成「每 MWh 的缺口吨数」与「全国货币量级」。"""
    tbl = DATUM["基准值表1_发电_tCO2每MWh"]
    rows = []
    for k, v in tbl.items():
        if v["2025"] == v["2026"]:
            rows.append({"机组类别": k, "2025基准值": v["2025"], "2026基准值": v["2026"],
                         "绝对收紧(t/MWh)": 0.0, "相对收紧%": 0.0,
                         "每GWh新增缺口(吨)": 0.0})
            continue
        d_abs = v["2025"] - v["2026"]
        d_rel = d_abs / v["2025"]
        rows.append({"机组类别": k, "2025基准值": v["2025"], "2026基准值": v["2026"],
                     "绝对收紧(t/MWh)": d_abs, "相对收紧%": d_rel * 100,
                     "每GWh新增缺口(吨)": d_abs * 1000})
    df = pd.DataFrame(rows)

    # 情景：假设全国燃煤发电量 5.0 万亿 kWh（≈2024 火电实际量级）落于三类燃煤机组。
    # 依据：2024 年全国火电发电量约 6.34 万亿 kWh，其中燃煤约 5.0 万亿 kWh。
    # 该值与其结构拆分为量级假设，用 ⓗ 标注，仅用于把「每 MWh 缺口」
    # 放大到「全国吨数」，不进入任何定价链。
    COAL_TWH = 5.0                          # 万亿 kWh
    COAL_MWH = COAL_TWH * 1e12 / 1e3        # 万亿kWh → MWh（1 TWh = 1e6 MWh）
    mix = {"I_300MW以上常规燃煤": 0.60, "II_300MW及以下常规燃煤": 0.20,
           "III_非常规燃煤含CFB": 0.20}      # ⓗ 按装机结构粗分
    tot = 0.0
    for _, r in df.iterrows():
        if r["机组类别"] in mix:
            vol_mwh = COAL_MWH * mix[r["机组类别"]]
            tot += r["绝对收紧(t/MWh)"] * vol_mwh
    df.attrs["全国新增缺口_亿吨_仅基准值收紧"] = tot / 1e8
    df.attrs["全国新增缺口_假设"] = (
        f"燃煤发电量 {COAL_TWH:.1f} 万亿 kWh（ⓗ），机组结构 {mix}（ⓗ）")
    return df


def q2_cross_check() -> dict:
    """用「综合基准值加权降幅 0.35%」独立复算一次，与分类别加总互校。"""
    d = DATUM["综合基准值年度降幅_编制说明"]["2026"]
    # 全国发电应清缴量（亿吨）：81.94 × 64.76%
    vol_power = COMPLIANCE_VOLUME * POWER_SHARE
    # 基准值下调 d ⇒ 同发电量下配额减少约 d 的比例 ⇒ 缺口增量 ≈ 应清缴量 × d
    delta_total = vol_power * abs(d)
    return {
        "发电应清缴量_亿吨": vol_power,
        "综合降幅": d,
        "口径A_按降幅推算新增缺口_亿吨": delta_total,
        "口径A_按97.9元每吨折_亿元": delta_total * 1e8 * 97.9 / 1e8,
    }


