# ── 表 5：数字映射（数值不变、标签全换）────────────────────────────────────
def build_number_map() -> pd.DataFrame:
    """
    以「论文口径 · 5 年期」为锚档，逐科目映射。
    数值全部读自 s14_保费结构分解.csv（该表本身由 s7 重算落盘），无硬编码。
    """
    S = load("s14_保费结构分解.csv")
    S["期限"] = S["期限"].astype(int)
    r = S[(S["标度档"] == "论文口径") & (S["期限"] == 5)].iloc[0]
    GP = float(r["GP_元每吨"])
    SI = float(r["SI_元每吨"])

    def amt(pct_col: str) -> float:
        return round(float(r[pct_col]) / 100.0 * GP, 1)

    rows = [
        ("限额 SI", "名义金额", SI, "—", "责任上限 → 结算封顶"),
        ("毛保费 GP", "前端权利金", GP, "100.00%", "锚：全部下游科目按其百分比折算"),
        ("纯风险占 GP", "期望结算额现值", amt("纯风险占GP%"), f"{float(r['纯风险占GP%']):.2f}%",
         "期望损失 → 期望结算"),
        ("风险附加占 GP", "风险溢价（尾部超出期望）", amt("风险附加占GP%"), f"{float(r['风险附加占GP%']):.2f}%",
         "TVaR₉₉ − E 口径不变"),
        ("资本成本占 GP", "资本占用补偿", amt("资本成本占GP%"), f"{float(r['资本成本占GP%']):.2f}%",
         "ρ ×(TVaR₉₉ − E) 口径不变"),
        ("附加费用占 GP", "运营成本加成", amt("附加费用占GP%"), f"{float(r['附加费用占GP%']):.2f}%",
         "同数值；不再受报行合一约束"),
        ("利润占 GP", "目标回报", amt("利润占GP%"), f"{float(r['利润占GP%']):.2f}%",
         "同数值；无监管约束"),
    ]
    df = pd.DataFrame(rows, columns=["保险口径科目", "名义合约口径科目", "数值（元/吨）", "占前端权利金%", "口径变化说明"])
    df.attrs["GP"] = GP
    df.attrs["SI"] = SI
    return df


