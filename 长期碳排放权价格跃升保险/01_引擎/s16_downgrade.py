    add("D1-3", f"可保性四要件中，L3 越界层至少 3 项「不满足」（实测 {n_l3_fail}/4）",
        n_l3_fail >= 3 and len(K) == 4)
    add("D1-4", "基础层 L0–L2 未被判为「不满足」（否则结论过度外推）",
        not bool(K["基础层 L0–L2"].str.contains("不满足").any()))

