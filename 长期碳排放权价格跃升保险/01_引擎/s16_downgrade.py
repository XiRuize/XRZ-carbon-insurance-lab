    L = load("s12_再保分层.csv")
    cov = I[I["覆盖越界年2028"] == "是"]
    p_floor = float(cov["触发概率_两年内"].min())
    p_ceil = float(cov["触发概率_两年内"].max())
    g_ratio = float(cov["低估倍数"].max()) / float(cov["低估倍数"].min())
    l3_share = L[L["层"] == "L3"].set_index("期限")["层厚占限额%"]
