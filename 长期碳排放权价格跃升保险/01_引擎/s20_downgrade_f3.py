def _cum_gap_rate(n: int) -> float:
    """n 年累计承保缺口率 = Σ (gap_rate_0 + gap_tighten × t)，t = 0..n−1。"""
    g = L1["gap_rate_0"] + L1["gap_tighten"] * np.arange(n)
    return float(np.sum(g))


def credit_exposure() -> tuple[pd.DataFrame, dict]:
    """暴露计量：由 SI × 承保缺口量 构建分档，不做虚假精度。"""
    S = load("s14_保费结构分解.csv")
    paper = S[S["标度档"] == "论文口径"].set_index("期限")
    si5 = float(paper.loc[5, "SI_元每吨"])
    cg5 = _cum_gap_rate(5)

    # 分档按「年排放量」（万吨 CO₂/年）；缺口量 W = E × 累计缺口率
    tiers = [
        ("甲", "特大型", 3000, None, "五大发电集团旗舰 + 头部地方能源集团"),
        ("乙", "大型", 800, 3000, "省级能源集团主力电厂"),
        ("丙", "中型", 200, 800, "区域发电企业"),
        ("丁", "小型", 0, 200, "自备电厂、地方热电厂、小型燃气电厂"),
    ]
    rows = []
    for code, name, lo, hi, note in tiers:
        w_lo = lo * cg5
        w_hi = (hi * cg5) if hi else None
        ead_lo = si5 * w_lo * 1e4 / 1e8            # 亿元
        ead_hi = (si5 * w_hi * 1e4 / 1e8) if w_hi else None
        rows.append({
            "档": code, "名称": name,
            "年排放量（万吨CO₂/年）": f"≥{lo}" if hi is None else f"{lo}–{hi}",
            "5年累计承保缺口量（万吨）": f"≥{w_lo:,.0f}" if w_hi is None else f"{w_lo:,.0f}–{w_hi:,.0f}",
            "单笔名义金额（亿元，5年期）": f"≥{ead_lo:,.0f}" if ead_hi is None else f"{ead_lo:,.0f}–{ead_hi:,.0f}",
            "业态": note,
            "家数（ⓗ 估算，待核）": "",
        })

    # 行业总量锚
    gen_vol_t = GEN_CLEAR_VOLUME_WT * 1e4                      # 吨
    gap_t = gen_vol_t * cg5
    total_notional = si5 * gap_t / 1e12                        # 万亿元
    avg_per_entity_ead = total_notional / N_ENTITY["发电"]     # 万亿元/家

    agg = {
        "发电应清缴量_万吨": GEN_CLEAR_VOLUME_WT,
        "发电应清缴量_占全国比例": GEN_CLEAR_VOLUME_WT * 1e4 / (COMPLIANCE_VOLUME * 1e8),
        "5年累计缺口率": cg5,
        "全行业累计缺口量_亿吨": gap_t / 1e8,
        "全行业满额承保名义金额_万亿元": total_notional,
        "单笔平均名义金额_亿元": avg_per_entity_ead * 1e4,
        "发电家数": N_ENTITY["发电"],
        "SI5_元每吨": si5,
    }
    return pd.DataFrame(rows), agg


