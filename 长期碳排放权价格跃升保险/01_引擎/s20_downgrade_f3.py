    add("F3-04", abs(AGG["5年累计缺口率"] - 0.45) < 1e-9,
        f"5 年累计缺口率 = {AGG['5年累计缺口率']:.4f}（= Σ(0.05+0.02t)，源自 _config.L1）")
    add("F3-05", AGG["全行业满额承保名义金额_万亿元"] > 50,
        f"全行业满额承保名义金额 {AGG['全行业满额承保名义金额_万亿元']:,.1f} 万亿元（量级结论：远超行业承载能力）")
    add("F3-06", len(PD) >= 6, f"PD 锚 ≥ 6 项（实测 {len(PD)}）")
    add("F3-07", PD["来源"].str.len().gt(0).all() and PD["可用性"].str.len().gt(0).all(),
        "每个 PD 锚均给出「来源」与「可用性」判断")
    add("F3-08", any("0.0479%" in v for v in PD["值"]), "含碳市场履约违约率 1/2087 = 0.0479%")
    add("F3-09", any("**0**" in v or "0" == v.strip() for v in PD["值"]), "含国企债券违约率 0")
    add("F3-10", len(EL) == 5, f"缔约结构分档 5 行（含互助池；实测 {len(EL)}）")
    # 一次因子模型自洽
    add("F3-11", abs(POOL["E_损失比例_无条件"] - POOL["p_ind"]) < 1e-12,
        "一次因子模型的无条件期望损失比例 = 个体 PD（自洽）")
    add("F3-12", POOL["P_损失比例_gt_10%"] < POOL["P_损失比例_gt_5%"] < POOL["P_损失比例_gt_1%"],
        f"尾部单调：P(>10%)={POOL['P_损失比例_gt_10%']:.2e} < P(>5%)={POOL['P_损失比例_gt_5%']:.2e} "
        f"< P(>1%)={POOL['P_损失比例_gt_1%']:.2e}")
    add("F3-13", POOL["条件损失比例_Z_-3"] > POOL["条件损失比例_Z_-2"] > POOL["p_ind"],
        f"条件损失比例随压力递增：Z=-2 → {POOL['条件损失比例_Z_-2']:.4%}"
        f"（{POOL['上修倍数_Z_-2']:.1f}×）；Z=-3 → {POOL['条件损失比例_Z_-3']:.4%}"
        f"（{POOL['上修倍数_Z_-3']:.1f}×）")
    add("F3-14", len(COND) == 5, f"条件 PD 敏感性 5 点（实测 {len(COND)}）")
    add("F3-15", len(WW) == 3, f"错向风险 3 情景（实测 {len(WW)}）")
    add("F3-16", any("wrong-way" in s for s in WW["错向方向"]), "明确标出经典错向风险情景（Regime B）")
    add("F3-17", any(("不得" in r["处置"]) or ("主风险" in r["处置"]) or ("仅作补充" in r["处置"])
                     for _, r in WW.iterrows()),
        "给出「碳配额质押不得作主要信用支持」的处置")
    add("F3-18", len(MIT) == 8, f"缓解措施 8 项（实测 {len(MIT)}）")
    add("F3-19", MIT["残余风险"].str.len().gt(0).all(), "每项缓解措施均给出残余风险")
    add("F3-20", len(SUP) == 6, f"信用支持阈值 6 档（实测 {len(SUP)}）")
    # 阈值求解自洽：代入 m* 后 EL 率 ≈ 目标
    sup_ok = True
    for _, r in SUP.iterrows():
        e = r["PD（年）"] * (1 - r["所需保证金比例 m*"])
        if r["所需保证金比例 m*"] > 0 and abs(e - TARGET_EL_RATE) > 1e-9:
            sup_ok = False
        if r["所需保证金比例 m*"] <= 0 and e > TARGET_EL_RATE + 1e-12:
            sup_ok = False
    add("F3-21", sup_ok, f"m* 求解自洽：达标后 EL 率 = 目标 {TARGET_EL_RATE:.2%}（或无需担保）")
    add("F3-22", (SUP["所需保证金比例 m*"] >= 0).all() and (SUP["所需保证金比例 m*"] <= 1).all(),
        "m* 全部落在 [0, 1]")
    # 关键结论：互助池需近乎全额保证金
    pool_m = 1 - TARGET_EL_RATE / POOL["条件损失比例_Z_-2"]
    add("F3-23", pool_m > 0.85,
        f"**核心结论**：互助池结构在条件 PD 下须收取 {pool_m:.1%} 保证金 ⇒ F3 的可行形态必然是"
        f"「准主权/高等级发起 + 分层缔约」，**不是**同业互助池")
    # 交叉一致性：数字映射
    N = load("s16_数字映射.csv")
    n_si = float(N[N["保险口径科目"] == "限额 SI"].iloc[0]["数值（元/吨）"])
    add("F3-24", abs(n_si - si5) < 1e-6, f"与 s16 数字映射的名义金额一致（{n_si:,.0f}）")

    V = pd.DataFrame(res)
    V.to_csv(OUT / "s20_验收.csv", index=False, encoding="utf-8-sig")
    if verbose:
        print(V.to_string(index=False))
        nf = int((V["结果"] == "FAIL").sum())
        print(f"\n  ⇒ {len(V) - nf} PASS / {nf} FAIL")
    return bool((V["结果"] == "PASS").all())


