def credit_support(pool_stats: dict) -> pd.DataFrame:
    """信用支持阈值：m* = 1 − 目标EL率 / PD（并给出深度压力档）。"""
    cases = [
        ("交易所 / 清算机构（准主权）", 0.00010, "结构 1a"),
        ("证券公司（AA）", 0.00050, "结构 1b"),
        ("商业银行（A）", 0.00200, "结构 1c"),
        ("商业银行（BBB / 城农商行）", 0.00500, "结构 1d"),
        ("互助池 · 条件 PD（Z = −2，上修 "
         f"{pool_stats['上修倍数_Z_-2']:.1f}×）", pool_stats["条件损失比例_Z_-2"], "结构 2"),
        ("互助池 · 深度压力（Z = −3，上修 "
         f"{pool_stats['上修倍数_Z_-3']:.1f}×）", pool_stats["条件损失比例_Z_-3"], "结构 2"),
    ]
    rows = []
    for name, pd_, struct in cases:
        m = max(0.0, 1.0 - TARGET_EL_RATE / pd_)
        rows.append({
            "对手方": name, "缔约结构": struct,
            "PD（年）": pd_, "PD（%）": pd_ * 100,
            "目标 EL 率": TARGET_EL_RATE,
            "所需保证金比例 m*": m,
            "m*（%）": m * 100,
            "无支持时 EL 率": pd_,
            "达标后 EL 率": pd_ * (1 - m),
            "结论": "无需追加信用支持" if m <= 0 else f"须收取 **{m:.1%}** 保证金 / 银行保函",
        })
    return pd.DataFrame(rows)


